"""Synthetic training data generator (§7, §42).

=========================================================================
 THIS DATA IS SYNTHETIC. IT IS NOT REAL STUDENT DATA AND IT IS NOT
 EVIDENCE OF ANY RESEARCH RESULT.
=========================================================================

Every row is generated from a documented statistical process, tagged
`provenance="SYNTHETIC"`, and any metric computed from it is labelled
"Prototype Evaluation - Synthetic Dataset" wherever it is displayed.

Why synthetic data exists here
------------------------------
The ML pipeline must be genuinely runnable and demonstrable before an
institution has collected real placement outcomes. Once real labelled outcomes
exist, `train.py` accepts a real CSV and the provenance label changes to REAL.

How labels are generated
------------------------
Labels are NOT a deterministic function of the features. A latent "true
readiness" is computed from a weighted combination, then:
  * Gaussian noise is added, representing unmeasured factors (interview-day
    performance, luck, role fit).
  * A small fraction of labels are deliberately flipped to an adjacent class,
    representing genuine label noise in real placement outcomes.

That noise is deliberate. A perfectly separable synthetic dataset would produce
a ~99% accuracy figure that means nothing whatsoever. The noise makes the
reported metrics informative about the *pipeline*, while still being explicitly
synthetic.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from app.ml.features import CLASS_LABELS, FEATURE_NAMES

PROVENANCE = "SYNTHETIC"

DISCLAIMER = (
    "Prototype Evaluation - Synthetic Dataset. These records were generated by a documented statistical "
    "process for development and demonstration. They are not real student data, and metrics derived from "
    "them must not be presented as empirical research results."
)

# Latent-readiness weights. Chosen to mirror the APIE prototype weighting so the
# ML model and the rule-based engine are at least telling a consistent story.
LATENT_WEIGHTS = {
    "atsScore": 0.10,
    "codingScore": 0.24,
    "technicalScore": 0.20,
    "hrScore": 0.08,
    "communicationScore": 0.14,
    "aptitudeScore": 0.10,
    "academicScore": 0.14,
}


def _archetype_profiles(rng: np.random.Generator, n: int) -> pd.DataFrame:
    """Draws students from four archetypes with realistic correlations.

    Real cohorts are not uniformly distributed: strong coders tend to also score
    well technically, and disengaged students have low counts everywhere. Mixing
    archetypes reproduces that structure, which is what makes a tree model's
    feature importances meaningful rather than arbitrary.
    """
    # Proportions loosely reflecting a typical engineering cohort.
    archetypes = rng.choice([0, 1, 2, 3], size=n, p=[0.22, 0.34, 0.30, 0.14])

    # (centre, spread) for the core academic/skill ability of each archetype.
    centres = {0: (32.0, 12.0), 1: (52.0, 12.0), 2: (70.0, 10.0), 3: (85.0, 7.0)}

    ability = np.array([rng.normal(*centres[int(a)]) for a in archetypes])
    ability = np.clip(ability, 5, 99)

    def correlated(scale: float, floor: float = 0.0) -> np.ndarray:
        """A score correlated with ability but with its own variance."""
        return np.clip(ability + rng.normal(0, scale, n), floor, 100)

    # Engagement drives how many activities the student has actually completed.
    engagement = np.clip((ability / 100) + rng.normal(0, 0.22, n), 0.02, 1.0)

    data = {
        "atsScore": correlated(16),
        "codingScore": correlated(18),
        "technicalScore": correlated(15),
        "hrScore": correlated(17),
        "communicationScore": correlated(16),
        "aptitudeScore": correlated(17),
        "academicScore": np.clip(ability + rng.normal(0, 10, n), 20, 100),
        "projectCount": np.round(np.clip(engagement * 6 + rng.normal(0, 1.2, n), 0, 12)),
        "certificationCount": np.round(np.clip(engagement * 5 + rng.normal(0, 1.5, n), 0, 12)),
        "internshipMonths": np.round(np.clip(engagement * 9 + rng.normal(0, 2.5, n), 0, 30)),
        "assessmentsTaken": np.round(np.clip(engagement * 16 + rng.normal(0, 3, n), 0, 40)),
        "interviewsTaken": np.round(np.clip(engagement * 12 + rng.normal(0, 3, n), 0, 40)),
        # Skill gaps fall as ability rises.
        "skillGapCount": np.round(np.clip(14 - (ability / 100) * 12 + rng.normal(0, 2.5, n), 0, 25)),
    }

    # Alumni feedback exists for only a minority of students; the rest get 0,
    # which is exactly the sparsity the real system will see.
    has_feedback = rng.random(n) < 0.38
    alumni = np.where(has_feedback, np.clip(ability + rng.normal(0, 12, n), 0, 100), 0.0)
    data["alumniFeedbackScore"] = alumni

    frame = pd.DataFrame(data)
    frame["_ability"] = ability
    frame["_hasAlumniFeedback"] = has_feedback
    return frame


def _assign_labels(frame: pd.DataFrame, rng: np.random.Generator) -> pd.Series:
    latent = sum(frame[column] * weight for column, weight in LATENT_WEIGHTS.items())

    # Evidence bonuses, mirroring the APIE modifiers.
    latent = latent + np.clip(frame["projectCount"], 0, 4) * 0.75
    latent = latent + np.clip(frame["certificationCount"], 0, 4) * 0.5
    latent = latent + np.clip(frame["internshipMonths"] / 6, 0, 2) * 1.5
    latent = latent - np.clip(frame["skillGapCount"], 0, 20) * 0.35

    # Alumni feedback nudges the latent score where it exists.
    feedback_delta = np.where(frame["_hasAlumniFeedback"], (frame["alumniFeedbackScore"] - 60) * 0.05, 0.0)
    latent = latent + feedback_delta

    # Unmeasured factors: interview-day performance, role fit, luck.
    latent = latent + rng.normal(0, 6.5, len(frame))
    latent = np.clip(latent, 0, 100)

    labels = pd.cut(
        latent,
        bins=[-0.01, 40, 60, 80, 100.01],
        labels=list(CLASS_LABELS),
    ).astype(str)

    # Deliberate label noise (~6%), flipped to an ADJACENT class only - real
    # mislabelling is a borderline call, not a wild one.
    noise_mask = rng.random(len(frame)) < 0.06
    label_index = {name: i for i, name in enumerate(CLASS_LABELS)}
    noisy = labels.copy()
    for i in np.flatnonzero(noise_mask):
        current = label_index[labels.iloc[i]]
        shift = rng.choice([-1, 1])
        noisy.iloc[i] = CLASS_LABELS[int(np.clip(current + shift, 0, len(CLASS_LABELS) - 1))]

    return noisy


def generate_dataset(n: int = 3000, seed: int = 42) -> pd.DataFrame:
    """Generates a labelled synthetic dataset.

    Returns a DataFrame with every column in `FEATURE_NAMES`, a `readinessBand`
    label, and a `provenance` column permanently marking it as SYNTHETIC.
    """
    rng = np.random.default_rng(seed)
    frame = _archetype_profiles(rng, n)
    frame["readinessBand"] = _assign_labels(frame, rng)

    frame = frame.drop(columns=["_ability", "_hasAlumniFeedback"])
    frame["provenance"] = PROVENANCE

    # Guarantee column order matches the model's expectation.
    return frame[[*FEATURE_NAMES, "readinessBand", "provenance"]]


def save_dataset(path, n: int = 3000, seed: int = 42) -> str:
    frame = generate_dataset(n=n, seed=seed)
    frame.to_csv(path, index=False)
    return str(path)
