"""LLM provider abstraction (§3, §45 rule 15).

Nothing above this module knows which provider is in use. Agents call
`get_llm().complete_json(...)` and receive a validated dict; swapping OpenAI for
Azure, a local Ollama model, or the offline mock is a configuration change.

Providers implemented here:
  openai  - any OpenAI-compatible /chat/completions endpoint
  azure   - Azure OpenAI deployments
  ollama  - local open-source models
  mock    - deterministic offline provider for development and demos

The mock provider is what lets the whole platform be demonstrated with no API
key and no network. Every response it produces is tagged
`provider="mock"` and carries a visible notice, so a mock result can never be
mistaken for a real model output (§41).
"""
from __future__ import annotations

import abc
import json
import re
import time
from dataclasses import dataclass, field
from typing import Any

import httpx

from app.core.config import settings
from app.core.errors import ProviderError
from app.core.logging import get_logger

log = get_logger(__name__)

MOCK_NOTICE = (
    "Generated by the offline mock provider (development mode). "
    "This is deterministic placeholder content, not a language-model result."
)


@dataclass
class LlmMessage:
    role: str  # "system" | "user" | "assistant"
    content: str


@dataclass
class LlmResult:
    text: str
    provider: str
    model: str
    latency_ms: int
    prompt_tokens: int = 0
    completion_tokens: int = 0
    degraded: bool = False
    notice: str | None = None
    raw: dict[str, Any] = field(default_factory=dict)


def _extract_json(text: str) -> Any:
    """Pull a JSON object out of a model response.

    Models frequently wrap JSON in prose or a ```json fence even when told not
    to, so this tries progressively more forgiving strategies before failing.
    """
    text = text.strip()
    if not text:
        raise ProviderError("The model returned an empty response.")

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    fence = re.search(r"```(?:json)?\s*(.*?)```", text, re.DOTALL)
    if fence:
        try:
            return json.loads(fence.group(1).strip())
        except json.JSONDecodeError:
            pass

    # Fall back to the outermost balanced object/array in the response.
    for opener, closer in (("{", "}"), ("[", "]")):
        start = text.find(opener)
        end = text.rfind(closer)
        if start != -1 and end > start:
            try:
                return json.loads(text[start : end + 1])
            except json.JSONDecodeError:
                continue

    raise ProviderError("The model response could not be parsed as JSON.")


class LlmProvider(abc.ABC):
    name: str = "base"

    @abc.abstractmethod
    async def complete(self, messages: list[LlmMessage], *, temperature: float | None = None,
                       max_tokens: int | None = None, json_mode: bool = False) -> LlmResult:
        ...

    async def complete_json(self, messages: list[LlmMessage], *, temperature: float | None = None,
                            max_tokens: int | None = None) -> tuple[Any, LlmResult]:
        result = await self.complete(messages, temperature=temperature, max_tokens=max_tokens, json_mode=True)
        return _extract_json(result.text), result

    async def health(self) -> dict[str, Any]:
        return {"provider": self.name, "reachable": True, "detail": None}


class OpenAiCompatibleProvider(LlmProvider):
    """Works with OpenAI and any API-compatible gateway (vLLM, LiteLLM, Groq...)."""

    name = "openai"

    def __init__(self) -> None:
        self.base_url = (settings.ai_base_url or "https://api.openai.com/v1").rstrip("/")
        self.model = settings.ai_model
        if not settings.ai_api_key:
            raise ProviderError(
                "AI_PROVIDER is set to 'openai' but AI_API_KEY is empty. "
                "Set the key in .env, or use AI_PROVIDER=mock for offline development."
            )

    def _headers(self) -> dict[str, str]:
        return {"Authorization": f"Bearer {settings.ai_api_key}", "Content-Type": "application/json"}

    def _url(self) -> str:
        return f"{self.base_url}/chat/completions"

    async def complete(self, messages, *, temperature=None, max_tokens=None, json_mode=False) -> LlmResult:
        payload: dict[str, Any] = {
            "model": self.model,
            "messages": [{"role": m.role, "content": m.content} for m in messages],
            "temperature": settings.ai_temperature if temperature is None else temperature,
            "max_tokens": max_tokens or settings.ai_max_tokens,
        }
        if json_mode:
            payload["response_format"] = {"type": "json_object"}

        start = time.perf_counter()
        try:
            async with httpx.AsyncClient(timeout=settings.ai_request_timeout) as client:
                response = await client.post(self._url(), headers=self._headers(), json=payload)
                response.raise_for_status()
                body = response.json()
        except httpx.HTTPStatusError as exc:
            detail = exc.response.text[:400]
            log.error("LLM provider returned an error", extra={"status": exc.response.status_code})
            raise ProviderError(f"The AI provider rejected the request ({exc.response.status_code}): {detail}") from exc
        except httpx.HTTPError as exc:
            raise ProviderError(f"The AI provider is unreachable: {exc}") from exc

        latency_ms = int((time.perf_counter() - start) * 1000)
        usage = body.get("usage", {})
        return LlmResult(
            text=body["choices"][0]["message"]["content"],
            provider=self.name,
            model=body.get("model", self.model),
            latency_ms=latency_ms,
            prompt_tokens=usage.get("prompt_tokens", 0),
            completion_tokens=usage.get("completion_tokens", 0),
        )

    async def health(self) -> dict[str, Any]:
        try:
            async with httpx.AsyncClient(timeout=8.0) as client:
                response = await client.get(f"{self.base_url}/models", headers=self._headers())
            return {"provider": self.name, "reachable": response.status_code < 500, "detail": None}
        except httpx.HTTPError as exc:
            return {"provider": self.name, "reachable": False, "detail": str(exc)}


class AzureOpenAiProvider(OpenAiCompatibleProvider):
    name = "azure"

    def __init__(self) -> None:  # noqa: D107 - deliberately does not call super()
        if not settings.azure_openai_endpoint or not settings.azure_openai_deployment:
            raise ProviderError(
                "AI_PROVIDER=azure requires AZURE_OPENAI_ENDPOINT and AZURE_OPENAI_DEPLOYMENT."
            )
        self.base_url = settings.azure_openai_endpoint.rstrip("/")
        self.model = settings.azure_openai_deployment

    def _headers(self) -> dict[str, str]:
        return {"api-key": settings.ai_api_key, "Content-Type": "application/json"}

    def _url(self) -> str:
        return (
            f"{self.base_url}/openai/deployments/{settings.azure_openai_deployment}"
            f"/chat/completions?api-version={settings.azure_openai_api_version}"
        )


class OllamaProvider(LlmProvider):
    """Local open-source models via Ollama's OpenAI-compatible chat endpoint."""

    name = "ollama"

    def __init__(self) -> None:
        self.base_url = (settings.ai_base_url or "http://127.0.0.1:11434").rstrip("/")
        self.model = settings.ai_model

    async def complete(self, messages, *, temperature=None, max_tokens=None, json_mode=False) -> LlmResult:
        payload: dict[str, Any] = {
            "model": self.model,
            "messages": [{"role": m.role, "content": m.content} for m in messages],
            "stream": False,
            "options": {
                "temperature": settings.ai_temperature if temperature is None else temperature,
                "num_predict": max_tokens or settings.ai_max_tokens,
            },
        }
        if json_mode:
            payload["format"] = "json"

        start = time.perf_counter()
        try:
            async with httpx.AsyncClient(timeout=settings.ai_request_timeout) as client:
                response = await client.post(f"{self.base_url}/api/chat", json=payload)
                response.raise_for_status()
                body = response.json()
        except httpx.HTTPError as exc:
            raise ProviderError(f"The local Ollama server is unreachable: {exc}") from exc

        return LlmResult(
            text=body["message"]["content"],
            provider=self.name,
            model=self.model,
            latency_ms=int((time.perf_counter() - start) * 1000),
            prompt_tokens=body.get("prompt_eval_count", 0),
            completion_tokens=body.get("eval_count", 0),
        )

    async def health(self) -> dict[str, Any]:
        try:
            async with httpx.AsyncClient(timeout=5.0) as client:
                response = await client.get(f"{self.base_url}/api/tags")
            return {"provider": self.name, "reachable": response.status_code == 200, "detail": None}
        except httpx.HTTPError as exc:
            return {"provider": self.name, "reachable": False, "detail": str(exc)}


class MockProvider(LlmProvider):
    """Deterministic offline provider.

    It does not attempt to imitate a language model. Instead it returns
    structured, schema-valid output derived from the prompt via
    `app.services.mock_content`, so every downstream code path - parsing,
    validation, scoring, persistence, UI rendering - is genuinely exercised
    without a network call.
    """

    name = "mock"

    async def complete(self, messages, *, temperature=None, max_tokens=None, json_mode=False) -> LlmResult:
        from app.services.mock_content import build_mock_response

        start = time.perf_counter()
        system = next((m.content for m in messages if m.role == "system"), "")
        user = next((m.content for m in reversed(messages) if m.role == "user"), "")
        text = build_mock_response(system, user, json_mode=json_mode)

        return LlmResult(
            text=text,
            provider=self.name,
            model="deterministic-mock-v1",
            latency_ms=int((time.perf_counter() - start) * 1000),
            degraded=True,
            notice=MOCK_NOTICE,
        )

    async def health(self) -> dict[str, Any]:
        return {"provider": self.name, "reachable": True, "detail": MOCK_NOTICE}


_PROVIDERS: dict[str, type[LlmProvider]] = {
    "openai": OpenAiCompatibleProvider,
    "azure": AzureOpenAiProvider,
    "ollama": OllamaProvider,
    "mock": MockProvider,
}

_instance: LlmProvider | None = None


def get_llm() -> LlmProvider:
    """Returns the configured provider, falling back to mock in development.

    A misconfigured provider in production is a hard failure: silently serving
    placeholder content to real users would be worse than an error.
    """
    global _instance
    if _instance is not None:
        return _instance

    provider_name = settings.ai_provider.lower().strip()
    provider_cls = _PROVIDERS.get(provider_name)

    if provider_cls is None:
        raise ProviderError(
            f"Unknown AI_PROVIDER '{settings.ai_provider}'. Supported: {', '.join(_PROVIDERS)}."
        )

    try:
        _instance = provider_cls()
    except ProviderError:
        if settings.is_production:
            raise
        log.warning(
            "Configured AI provider is unavailable; falling back to the offline mock provider. "
            "Results will be clearly labelled as mock output.",
            extra={"configured": provider_name},
        )
        _instance = MockProvider()

    log.info("LLM provider ready", extra={"provider": _instance.name, "model": settings.ai_model})
    return _instance


def reset_llm() -> None:
    """Clears the cached provider. Used by tests and by config hot-reload."""
    global _instance
    _instance = None
