export async function buildInstitutionReport(filters: {
  department?: string;
  batch?: string;
}): Promise<Buffer> {
  const { getPlacementAnalytics } = await import('./analytics.service');
  const analytics = await getPlacementAnalytics(filters);

  return render((doc) => {
    header(
      doc,
      filters.department ? `Department Report: ${filters.department}` : 'Institution Placement Report',
      [filters.batch && `Batch ${filters.batch}`].filter(Boolean).join(' · ') || 'All batches',
    );

    sectionTitle(doc, 'Cohort Summary');
    keyValueGrid(doc, [
      ['Total students', String(analytics.totals.students)],
      ['Active (last 30 days)', String(analytics.totals.activeStudents)],
      ['Average readiness', `${analytics.averages.prs}/100`],
      ['Placement ready', `${analytics.placementReadyPercentage}%`],
      ['At risk', `${analytics.atRiskPercentage}%`],
      ['Verified alumni', String(analytics.totals.verifiedAlumni)],
      ['Assessments taken', String(analytics.totals.assessmentsTaken)],
      ['Interviews taken', String(analytics.totals.interviewsTaken)],
    ]);

    sectionTitle(doc, 'Average Component Scores');
    scoreBar(doc, 'Resume / ATS', analytics.averages.ats);
    scoreBar(doc, 'Coding', analytics.averages.coding);
    scoreBar(doc, 'Technical interview', analytics.averages.technical);
    scoreBar(doc, 'HR interview', analytics.averages.hr);
    scoreBar(doc, 'Communication', analytics.averages.communication);
    scoreBar(doc, 'Aptitude', analytics.averages.aptitude);

    sectionTitle(doc, 'Readiness Distribution');
    for (const item of analytics.readinessDistribution) {
      scoreBar(doc, `${item.band.replace(/_/g, ' ')} (${item.count})`, item.percentage, 100, bandColor(item.band));
    }

    if (analytics.commonSkillGaps.length) {
      sectionTitle(doc, 'Most Common Skill Gaps');
      bulletList(
        doc,
        analytics.commonSkillGaps.map((g) => `${g.skill} — ${g.count} student(s), average gap ${g.averageGap}/100, ${g.severity} severity`),
      );
    }

    if (analytics.departmentComparison.length > 1) {
      sectionTitle(doc, 'Department Comparison');
      for (const dept of analytics.departmentComparison) {
        scoreBar(doc, `${dept.department} (${dept.students})`, dept.averagePrs);
      }
    }

    if (analytics.topTargetCompanies.length) {
      sectionTitle(doc, 'Most Targeted Companies');
      bulletList(doc, analytics.topTargetCompanies.map((c) => `${c.company} — ${c.count} student(s)`));
    }

    if (analytics.alumniParticipation.length) {
      sectionTitle(doc, 'Alumni Participation');
      bulletList(
        doc,
        analytics.alumniParticipation.map((a) => `${a.alumniName} (${a.company}) — ${a.sessions} session(s), rating ${a.averageRating}/5`),
      );
    }
  });
}

export async function buildSkillGapReport(filters: { department?: string; batch?: string }): Promise<Buffer> {
  const { getPlacementAnalytics } = await import('./analytics.service');
  const analytics = await getPlacementAnalytics(filters);

  return render((doc) => {
    header(doc, 'Institutional Skill Gap Report', filters.department ?? 'All departments');

    sectionTitle(doc, 'Scope');
    keyValueGrid(doc, [
      ['Students analysed', String(analytics.totals.students)],
      ['Distinct gaps found', String(analytics.commonSkillGaps.length)],
    ]);

    sectionTitle(doc, 'Gap Prevalence');
    for (const gap of analytics.commonSkillGaps) {
      scoreBar(
        doc,
        `${gap.skill} (${gap.count})`,
        analytics.totals.students ? (gap.count / analytics.totals.students) * 100 : 0,
        100,
        gap.severity === 'CRITICAL' ? BRAND.danger : gap.severity === 'HIGH' ? BRAND.warning : BRAND.primary,
      );
    }

    sectionTitle(doc, 'Suggested Interventions');
    bulletList(
      doc,
      analytics.commonSkillGaps
        .slice(0, 5)
        .map(
          (gap) =>
            `Run a cohort workshop on ${gap.skill}: it affects ${gap.count} student(s) ` +
            `(${analytics.totals.students ? Math.round((gap.count / analytics.totals.students) * 100) : 0}% of this cohort).`,
        ),
    );
  });
}

export async function buildStudentPerformanceReport(studentId: Types.ObjectId): Promise<Buffer> {
  const { profile, user } = await studentHeaderInfo(studentId);

  const [readiness, attempts, interviews, gaps] = await Promise.all([
    PlacementReadiness.findOne({ studentId, isLatest: true }).lean(),
    AssessmentAttempt.find({ studentId, status: 'EVALUATED' })
      .populate<{ assessmentId: { title: string; type: string } }>('assessmentId', 'title type')
      .sort({ submittedAt: -1 })
      .limit(15)
      .lean(),
    InterviewEvaluation.find({ studentId }).sort({ createdAt: -1 }).limit(10).lean(),
    SkillGap.find({ studentId, resolved: false }).sort({ severity: 1 }).limit(12).lean(),
  ]);

  return render((doc) => {
    header(doc, 'Student Performance Report', `${user?.fullName ?? ''} · ${profile.rollNumber ?? ''} · ${profile.department ?? ''}`);

    sectionTitle(doc, 'Profile');
    keyValueGrid(doc, [
      ['Roll number', profile.rollNumber ?? 'Not set'],
      ['Department', profile.department ?? 'Not set'],
      ['Batch', profile.batch ?? 'Not set'],
      ['CGPA', profile.cgpa ? String(profile.cgpa) : 'Not set'],
      ['Backlogs', String(profile.backlogs ?? 0)],
      ['Profile completion', `${profile.profileCompletion}%`],
      ['Projects', String(profile.projects.length)],
      ['Certifications', String(profile.certifications.length)],
    ]);

    if (readiness) {
      sectionTitle(doc, 'Placement Readiness');
      scoreBar(doc, 'Overall readiness', readiness.score, 100, bandColor(readiness.band));
      for (const component of readiness.components as Array<{ label: string; normalized: number; raw: number | null }>) {
        if (component.raw !== null) scoreBar(doc, component.label, component.normalized);
      }
    } else {
      sectionTitle(doc, 'Placement Readiness');
      doc.font('Helvetica-Oblique').fontSize(9.5).fillColor(BRAND.muted)
        .text('No readiness score has been computed yet. The student has not completed enough activities.');
      doc.fillColor(BRAND.text);
    }

    if (attempts.length) {
      sectionTitle(doc, 'Assessment History');
      bulletList(
        doc,
        attempts.map((a) => {
          const assessment = a.assessmentId as unknown as { title?: string; type?: string };
          return `${assessment?.title ?? 'Assessment'} (${assessment?.type ?? ''}) — ${Math.round(a.percentage ?? 0)}% on ${new Date(a.submittedAt!).toLocaleDateString()}${a.integrityRisk !== 'LOW' ? ` [integrity: ${a.integrityRisk}]` : ''}`;
        }),
      );
    }

    if (interviews.length) {
      sectionTitle(doc, 'Interview History');
      bulletList(
        doc,
        interviews.map((i) => `${i.mode.replace(/_/g, ' ')} — ${Math.round(i.overallScore)}/100 on ${new Date(i.createdAt).toLocaleDateString()}`),
      );
    }

    if (gaps.length) {
      sectionTitle(doc, 'Open Skill Gaps');
      bulletList(doc, gaps.map((g) => `${g.skill} — ${g.severity}`));
    }
  });
}

/** Maps a report type onto its builder, so the controller stays a thin router. */
export const REPORT_BUILDERS: Record<string, (studentId: Types.ObjectId, ref?: string) => Promise<Buffer>> = {
  [ReportType.RESUME_ANALYSIS]: (id, ref) => buildResumeReport(id, ref),
  [ReportType.ATS]: (id, ref) => buildResumeReport(id, ref),
  [ReportType.PLACEMENT_READINESS]: (id) => buildReadinessReport(id),
  [ReportType.INTERVIEW]: (id, ref) => {
    if (!ref) throw ApiError.badRequest('An interview session id is required for this report.');
    return buildInterviewReport(id, ref);
  },
  [ReportType.CODING]: (id) => buildCodingReport(id),
  [ReportType.ALUMNI_FEEDBACK]: (id) => buildAlumniFeedbackReport(id),
  [ReportType.STUDENT_PERFORMANCE]: (id) => buildStudentPerformanceReport(id),
};

export function reportFilename(type: string, name?: string): string {
  const slug = (name ?? 'report').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);
  const date = new Date().toISOString().slice(0, 10);
  return `careerpilot-${type.toLowerCase().replace(/_/g, '-')}-${slug}-${date}.pdf`;
}
