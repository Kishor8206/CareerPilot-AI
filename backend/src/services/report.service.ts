export async function buildResumeReport(studentId: Types.ObjectId, analysisId?: string): Promise<Buffer> {
  const { profile, user } = await studentHeaderInfo(studentId);
  const analysis = analysisId
    ? await ResumeAnalysis.findOne({ _id: analysisId, studentId }).lean()
    : await ResumeAnalysis.findOne({ studentId }).sort({ createdAt: -1 }).lean();

  if (!analysis) throw ApiError.notFound('Resume analysis');
  const parsed = analysis.parsed as Record<string, any>;

  return render((doc) => {
    header(doc, 'Resume Analysis & ATS Report', `${user?.fullName ?? ''} · ${profile.department ?? ''}`);

    sectionTitle(doc, 'Overall ATS Score');
    scoreBar(doc, 'ATS Score', analysis.atsScore, 100, analysis.atsScore >= 70 ? BRAND.success : analysis.atsScore >= 50 ? BRAND.warning : BRAND.danger);
    doc.font('Helvetica-Oblique').fontSize(8).fillColor(BRAND.muted).text(
      'This score approximates how an applicant-tracking system and a recruiter would read your resume. ' +
        'It is not the output of any specific employer\'s ATS.',
      { width: doc.page.width - 100 },
    );
    doc.fillColor(BRAND.text).moveDown(0.5);

    sectionTitle(doc, 'Score Breakdown');
    for (const item of analysis.breakdown as Array<{ criterion: string; score: number; maxScore: number; detail: string }>) {
      scoreBar(doc, item.criterion, item.score, item.maxScore);
      ensureSpace(doc, 20);
      doc.font('Helvetica').fontSize(8).fillColor(BRAND.muted).text(safe(item.detail), 50, doc.y, { width: doc.page.width - 100 });
      doc.moveDown(0.35);
      doc.fillColor(BRAND.text);
    }

    sectionTitle(doc, 'Extracted Profile');
    keyValueGrid(doc, [
      ['Name', parsed.name ?? 'Not detected'],
      ['Email', parsed.email ?? 'Not detected'],
      ['Phone', parsed.phone ?? 'Not detected'],
      ['CGPA', parsed.cgpa ? String(parsed.cgpa) : 'Not detected'],
      ['Skills detected', String((parsed.skills ?? []).length)],
      ['Projects', String((parsed.projects ?? []).length)],
      ['Internships', String((parsed.internships ?? []).length)],
      ['Certifications', String((parsed.certifications ?? []).length)],
    ]);

    sectionTitle(doc, 'Skills Identified');
    doc.font('Helvetica').fontSize(9.5).text(safe((parsed.skills ?? []).join(' · ')) || 'None detected.', { width: doc.page.width - 100 });

    if (analysis.matchedKeywords.length || analysis.missingKeywords.length) {
      sectionTitle(doc, 'Job Description Keyword Match');
      doc.font('Helvetica-Bold').fontSize(9.5).fillColor(BRAND.success).text('Matched keywords');
      doc.font('Helvetica').fillColor(BRAND.text).fontSize(9).text(safe(analysis.matchedKeywords.join(', ')) || 'None');
      doc.moveDown(0.4);
      doc.font('Helvetica-Bold').fontSize(9.5).fillColor(BRAND.danger).text('Missing keywords');
      doc.font('Helvetica').fillColor(BRAND.text).fontSize(9).text(safe(analysis.missingKeywords.join(', ')) || 'None');
    }

    sectionTitle(doc, 'Strengths');
    bulletList(doc, analysis.strengths, BRAND.success);

    sectionTitle(doc, 'Areas to Improve');
    bulletList(doc, analysis.weaknesses, BRAND.danger);

    sectionTitle(doc, 'Formatting Recommendations');
    bulletList(doc, analysis.formattingRecommendations);

    if (analysis.jobSpecificRecommendations.length) {
      sectionTitle(doc, 'Job-Specific Recommendations');
      bulletList(doc, analysis.jobSpecificRecommendations);
    }
  });
}

export async function buildReadinessReport(studentId: Types.ObjectId): Promise<Buffer> {
  const { profile, user } = await studentHeaderInfo(studentId);

  const [readiness, gaps, history] = await Promise.all([
    PlacementReadiness.findOne({ studentId, isLatest: true }).lean(),
    SkillGap.find({ studentId, resolved: false }).sort({ severity: 1, gap: -1 }).limit(15).lean(),
    PlacementReadiness.find({ studentId }).sort({ computedAt: -1 }).limit(8).select('score band computedAt').lean(),
  ]);

  if (!readiness) throw ApiError.notFound('Placement readiness record');

  return render((doc) => {
    header(doc, 'Placement Readiness Report', `${user?.fullName ?? ''} · ${profile.rollNumber ?? ''} · ${profile.department ?? ''}`);

    // Headline score block.
    const boxTop = doc.y;
    doc.roundedRect(50, boxTop, doc.page.width - 100, 68, 8).fill('#f1f5f9');
    doc.fillColor(bandColor(readiness.band)).font('Helvetica-Bold').fontSize(34)
      .text(String(Math.round(readiness.score)), 68, boxTop + 14, { width: 90 });
    doc.fillColor(BRAND.muted).font('Helvetica').fontSize(8).text('OUT OF 100', 68, boxTop + 50, { width: 90 });
    doc.fillColor(BRAND.text).font('Helvetica-Bold').fontSize(15)
      .text(readiness.band.replace(/_/g, ' '), 175, boxTop + 18, { width: 250 });
    doc.font('Helvetica').fontSize(9).fillColor(BRAND.muted)
      .text(
        readiness.delta !== null && readiness.delta !== undefined
          ? `${readiness.delta >= 0 ? '+' : ''}${readiness.delta} points since the previous computation`
          : 'First readiness computation',
        175,
        boxTop + 40,
        { width: 250 },
      );
    doc.y = boxTop + 82;
    doc.fillColor(BRAND.text);

    sectionTitle(doc, 'Component Scores');
    for (const component of readiness.components as Array<{ label: string; normalized: number; raw: number | null; weight: number; stale: boolean }>) {
      scoreBar(
        doc,
        `${component.label} (${Math.round(component.weight * 100)}%)`,
        component.normalized,
        100,
        component.raw === null ? BRAND.light : component.normalized >= 70 ? BRAND.success : component.normalized >= 50 ? BRAND.warning : BRAND.danger,
      );
      if (component.raw === null) {
        doc.font('Helvetica-Oblique').fontSize(7.5).fillColor(BRAND.muted).text('No evidence recorded yet', 205, doc.y - 18);
        doc.fillColor(BRAND.text);
      } else if (component.stale) {
        doc.font('Helvetica-Oblique').fontSize(7.5).fillColor(BRAND.warning).text('Evidence is stale - reassessment suggested', 205, doc.y - 18);
        doc.fillColor(BRAND.text);
      }
    }

    const modifiers = readiness.modifiers as Array<{ label: string; delta: number; reason: string }>;
    if (modifiers?.length) {
      sectionTitle(doc, 'Score Modifiers');
      bulletList(doc, modifiers.map((m) => `${m.label}: ${m.delta >= 0 ? '+' : ''}${m.delta} — ${m.reason}`));
    }

    sectionTitle(doc, 'Strengths');
    bulletList(doc, readiness.strengths, BRAND.success);

    sectionTitle(doc, 'Areas Needing Work');
    bulletList(doc, readiness.weaknesses, BRAND.danger);

    if (gaps.length) {
      sectionTitle(doc, 'Skill Gaps');
      bulletList(doc, gaps.map((g) => `${g.skill} — ${g.severity} severity (gap ${Math.round(g.gap)}/100)${g.relatedRoles.length ? `, required for ${g.relatedRoles.join(', ')}` : ''}`));
    }

    const roleReadiness = readiness.targetRoleReadiness as Array<{ roleTitle: string; score: number; band: string; missingSkills: string[] }>;
    if (roleReadiness?.length) {
      sectionTitle(doc, 'Target Role Readiness');
      for (const role of roleReadiness) {
        scoreBar(doc, role.roleTitle, role.score, 100, bandColor(role.band));
        if (role.missingSkills?.length) {
          doc.font('Helvetica').fontSize(8).fillColor(BRAND.muted)
            .text(`Missing: ${safe(role.missingSkills.join(', '))}`, 205, doc.y - 18, { width: doc.page.width - 320 });
          doc.fillColor(BRAND.text);
          doc.moveDown(0.3);
        }
      }
    }

    const ml = readiness.mlPrediction as Record<string, any> | null;
    if (ml) {
      sectionTitle(doc, 'Machine Learning Second Opinion');
      keyValueGrid(doc, [
        ['Predicted band', String(ml.band ?? '').replace(/_/g, ' ')],
        ['Confidence', `${Math.round((ml.confidence ?? 0) * 100)}%`],
        ['Model', `${ml.algorithm ?? 'unknown'} v${ml.modelVersion ?? '?'}`],
        ['Trained on', String(ml.trainedOn ?? 'SYNTHETIC')],
      ]);
      doc.font('Helvetica-Oblique').fontSize(8).fillColor(BRAND.muted)
        .text(safe(ml.disclaimer ?? ''), { width: doc.page.width - 100 });
      doc.fillColor(BRAND.text);
    }

    if (history.length > 1) {
      sectionTitle(doc, 'Readiness History');
      bulletList(
        doc,
        history.map((h) => `${new Date(h.computedAt).toLocaleDateString()} — ${Math.round(h.score)}/100 (${h.band.replace(/_/g, ' ')})`),
      );
    }

    sectionTitle(doc, 'Scoring Model');
    doc.font('Helvetica').fontSize(8.5).fillColor(BRAND.muted).text(safe(readiness.modelDisclaimer), { width: doc.page.width - 100 });
    doc.moveDown(0.3);
    doc.text(
      `Weights applied (version ${readiness.weightsVersion}): ` +
        Object.entries(readiness.weightsSnapshot as Record<string, number>)
          .map(([k, v]) => `${k} ${Math.round(v * 100)}%`)
          .join(' · '),
      { width: doc.page.width - 100 },
    );
    doc.fillColor(BRAND.text);
  });
}

export async function buildInterviewReport(studentId: Types.ObjectId, sessionId: string): Promise<Buffer> {
  const { user } = await studentHeaderInfo(studentId);
  const evaluation = await InterviewEvaluation.findOne({ sessionId, studentId }).lean();
  if (!evaluation) throw ApiError.notFound('Interview evaluation');

  return render((doc) => {
    header(doc, 'Mock Interview Report', `${user?.fullName ?? ''} · ${evaluation.mode.replace(/_/g, ' ')} interview`);

    sectionTitle(doc, 'Performance Summary');
    scoreBar(doc, 'Overall', evaluation.overallScore, 100, bandColor(evaluation.overallScore >= 60 ? 'PLACEMENT_READY' : 'AT_RISK'));
    scoreBar(doc, 'Technical content', evaluation.technicalScore);
    scoreBar(doc, 'Communication', evaluation.communicationScore);
    scoreBar(doc, 'Answer structure', evaluation.structureScore);
    scoreBar(doc, 'Delivery indicator', evaluation.confidenceIndicatorScore);

    doc.moveDown(0.2);
    doc.font('Helvetica-Oblique').fontSize(8).fillColor(BRAND.muted).text(
      'The delivery indicator is derived from objective signals only — answer length adequacy and filler-word ' +
        'rate. It is not an assessment of personality, emotion or confidence as a trait.',
      { width: doc.page.width - 100 },
    );
    doc.fillColor(BRAND.text);

    sectionTitle(doc, 'Summary');
    doc.font('Helvetica').fontSize(10).text(safe(evaluation.summary), { width: doc.page.width - 100 });

    sectionTitle(doc, 'Strengths');
    bulletList(doc, evaluation.strengths, BRAND.success);

    sectionTitle(doc, 'Areas to Improve');
    bulletList(doc, evaluation.weaknesses, BRAND.danger);

    sectionTitle(doc, 'Recommendations');
    bulletList(doc, evaluation.recommendations);

    sectionTitle(doc, 'Question-by-Question Feedback');
    for (const [index, item] of evaluation.perQuestion.entries()) {
      ensureSpace(doc, 80);
      doc.font('Helvetica-Bold').fontSize(9.5).fillColor(BRAND.text)
        .text(`Q${index + 1}. ${safe(item.question)}`, { width: doc.page.width - 100 });
      doc.font('Helvetica-Bold').fontSize(9).fillColor(item.score >= 60 ? BRAND.success : BRAND.warning)
        .text(`Score: ${Math.round(item.score)}/100`);
      doc.font('Helvetica').fontSize(9).fillColor(BRAND.muted)
        .text(safe(item.feedback), { width: doc.page.width - 100 });
      doc.fillColor(BRAND.text).moveDown(0.5);
    }

    sectionTitle(doc, 'Important Note');
    doc.font('Helvetica-Oblique').fontSize(8.5).fillColor(BRAND.muted)
      .text(safe(evaluation.disclaimer), { width: doc.page.width - 100 });
  });
}

export async function buildCodingReport(studentId: Types.ObjectId): Promise<Buffer> {
  const { user } = await studentHeaderInfo(studentId);
  const { CodingSubmission } = await import('../models/CodingSubmission');

  const submissions = await CodingSubmission.find({ studentId, isDraftRun: false })
    .populate<{ problemId: { title: string; difficulty: string; tags: string[] } }>('problemId', 'title difficulty tags')
    .sort({ createdAt: -1 })
    .limit(25)
    .lean();

  if (!submissions.length) throw ApiError.notFound('Coding submissions');

  const bestByProblem = new Map<string, number>();
  for (const s of submissions) {
    const key = String((s.problemId as unknown as { _id?: unknown })?._id ?? s.problemId);
    bestByProblem.set(key, Math.max(bestByProblem.get(key) ?? 0, s.score));
  }
  const scores = [...bestByProblem.values()];
  const averageScore = scores.reduce((a, b) => a + b, 0) / scores.length;

  return render((doc) => {
    header(doc, 'Coding Assessment Report', user?.fullName ?? '');

    sectionTitle(doc, 'Overview');
    keyValueGrid(doc, [
      ['Problems attempted', String(bestByProblem.size)],
      ['Fully solved', String(scores.filter((s) => s === 100).length)],
      ['Average best score', `${Math.round(averageScore)}/100`],
      ['Total submissions', String(submissions.length)],
    ]);

    scoreBar(doc, 'Average coding score', averageScore, 100, averageScore >= 70 ? BRAND.success : averageScore >= 40 ? BRAND.warning : BRAND.danger);

    sectionTitle(doc, 'Submissions');
    for (const submission of submissions.slice(0, 15)) {
      ensureSpace(doc, 70);
      const problem = submission.problemId as unknown as { title?: string; difficulty?: string };
      doc.font('Helvetica-Bold').fontSize(9.5).text(safe(problem?.title ?? 'Problem'));
      doc.font('Helvetica').fontSize(8.5).fillColor(BRAND.muted).text(
        `${problem?.difficulty ?? ''} · ${submission.language} · ${submission.execution.passedCount}/${submission.execution.totalCount} test cases · ` +
          `${submission.execution.status} · ${new Date(submission.createdAt).toLocaleDateString()}`,
      );
      doc.fillColor(BRAND.text);

      const review = submission.aiReview as Record<string, any> | null;
      if (review?.complexityEstimate) {
        doc.font('Helvetica').fontSize(8.5).fillColor(BRAND.muted).text(
          `Estimated complexity: time ${review.complexityEstimate.time}, space ${review.complexityEstimate.space}`,
        );
        doc.fillColor(BRAND.text);
      }
      doc.moveDown(0.45);
    }
  });
}

export async function buildAlumniFeedbackReport(studentId: Types.ObjectId): Promise<Buffer> {
  const { user } = await studentHeaderInfo(studentId);
  const feedback = await AlumniFeedback.find({ studentId })
    .populate<{ alumniId: { company: string; designation: string } }>('alumniId', 'company designation')
    .sort({ createdAt: -1 })
    .limit(10)
    .lean();

  if (!feedback.length) throw ApiError.notFound('Alumni feedback');

  return render((doc) => {
    header(doc, 'Alumni Feedback Report', user?.fullName ?? '');

    sectionTitle(doc, 'Overview');
    const averageScore = feedback.reduce((sum, f) => sum + f.overallScore, 0) / feedback.length;
    keyValueGrid(doc, [
      ['Sessions with feedback', String(feedback.length)],
      ['Average score', `${Math.round(averageScore)}/100`],
    ]);

    for (const item of feedback) {
      ensureSpace(doc, 160);
      const alumni = item.alumniId as unknown as { company?: string; designation?: string };
      sectionTitle(doc, `${safe(alumni?.designation ?? 'Mentor')} at ${safe(alumni?.company ?? '')}`);
      doc.font('Helvetica').fontSize(8.5).fillColor(BRAND.muted)
        .text(`${new Date(item.createdAt).toLocaleDateString()} · Recommendation: ${item.recommendation.replace(/_/g, ' ')}`);
      doc.fillColor(BRAND.text).moveDown(0.3);

      scoreBar(doc, 'Technical knowledge', item.technicalKnowledge, 10);
      scoreBar(doc, 'Communication', item.communication, 10);
      scoreBar(doc, 'Problem solving', item.problemSolving, 10);
      scoreBar(doc, 'Confidence', item.confidence, 10);
      scoreBar(doc, 'Role suitability', item.roleSuitability, 10);

      if (item.strengths.length) {
        doc.font('Helvetica-Bold').fontSize(9).fillColor(BRAND.success).text('Strengths');
        doc.fillColor(BRAND.text);
        bulletList(doc, item.strengths);
      }
      if (item.improvements.length) {
        doc.font('Helvetica-Bold').fontSize(9).fillColor(BRAND.danger).text('Improvements');
        doc.fillColor(BRAND.text);
        bulletList(doc, item.improvements);
      }
      if (item.comments) {
        doc.font('Helvetica-Bold').fontSize(9).text('Comments');
        doc.font('Helvetica').fontSize(9).fillColor(BRAND.muted).text(safe(item.comments), { width: doc.page.width - 100 });
        doc.fillColor(BRAND.text);
      }
      doc.moveDown(0.5);
    }
  });
}

