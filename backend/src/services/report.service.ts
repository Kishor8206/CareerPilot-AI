/**
 * PDF report generation (§26).
 *
 * Reports are built in memory and streamed to the response; nothing is written
 * to disk, so there is no temporary-file cleanup to get wrong and no path for a
 * report to leak to another user.
 *
 * Every report carries the prototype disclaimer, because these documents are
 * the artefacts most likely to be shown to a third party out of context.
 */

const BRAND = {
  primary: '#1e40af',
  text: '#0f172a',
  muted: '#64748b',
  light: '#e2e8f0',
  success: '#15803d',
  warning: '#b45309',
  danger: '#b91c1c',
};

const DISCLAIMER =
  'Generated by CareerPilot AI, an academic prototype. Scores are produced by a configurable rule-based ' +
  'model and AI analysis for preparation purposes. They are not a prediction of employment and must not be ' +
  'used as a hiring or academic decision.';

type Doc = PDFKit.PDFDocument;

/** Guards against control characters from parsed resumes corrupting the PDF. */
function safe(text: unknown): string {
  return stripControlCharacters(String(text ?? '')).slice(0, 4000);
}

function bandColor(band: string): string {
  switch (band) {
    case 'HIGHLY_READY':
    case 'PLACEMENT_READY':
      return BRAND.success;
    case 'NEEDS_IMPROVEMENT':
      return BRAND.warning;
    default:
      return BRAND.danger;
  }
}

function header(doc: Doc, title: string, subtitle?: string): void {
  doc.rect(0, 0, doc.page.width, 90).fill(BRAND.primary);
  doc.fillColor('#ffffff').fontSize(20).font('Helvetica-Bold').text('CareerPilot AI', 50, 28);
  doc.fontSize(9).font('Helvetica').text('Agentic AI-Based Placement Preparation Platform', 50, 52);
  doc.fontSize(9).text(new Date().toLocaleString(), 50, 66);

  doc.fillColor(BRAND.text).font('Helvetica-Bold').fontSize(17).text(title, 50, 115);
  if (subtitle) {
    doc.font('Helvetica').fontSize(10).fillColor(BRAND.muted).text(safe(subtitle), 50, 138);
  }
  doc.moveTo(50, subtitle ? 158 : 140).lineTo(doc.page.width - 50, subtitle ? 158 : 140).strokeColor(BRAND.light).stroke();
  doc.y = subtitle ? 172 : 154;
  doc.fillColor(BRAND.text);
}

function sectionTitle(doc: Doc, title: string): void {
  ensureSpace(doc, 60);
  doc.moveDown(0.6);
  doc.font('Helvetica-Bold').fontSize(12).fillColor(BRAND.primary).text(title);
  doc.moveDown(0.3);
  doc.font('Helvetica').fontSize(10).fillColor(BRAND.text);
}

/** Adds a page when the remaining space is too small for the next block. */
function ensureSpace(doc: Doc, needed: number): void {
  if (doc.y + needed > doc.page.height - 70) {
    doc.addPage();
    doc.y = 60;
  }
}

function keyValueGrid(doc: Doc, entries: Array<[string, string]>): void {
  const columnWidth = (doc.page.width - 100) / 2;
  let column = 0;
  let rowTop = doc.y;

  for (const [label, value] of entries) {
    const x = 50 + column * columnWidth;
    doc.font('Helvetica').fontSize(8).fillColor(BRAND.muted).text(label.toUpperCase(), x, rowTop, { width: columnWidth - 12 });
    doc.font('Helvetica-Bold').fontSize(10).fillColor(BRAND.text).text(safe(value), x, rowTop + 12, { width: columnWidth - 12 });

    column += 1;
    if (column === 2) {
      column = 0;
      rowTop += 34;
      ensureSpace(doc, 40);
    }
  }
  doc.y = column === 0 ? rowTop : rowTop + 34;
  doc.moveDown(0.4);
}

/** Horizontal score bar; the visual is what makes a report scannable. */
function scoreBar(doc: Doc, label: string, score: number, max = 100, color = BRAND.primary): void {
  ensureSpace(doc, 34);
  const top = doc.y;
  const barWidth = doc.page.width - 100 - 190;

  doc.font('Helvetica').fontSize(9).fillColor(BRAND.text).text(safe(label), 50, top + 2, { width: 150 });
  doc.roundedRect(205, top, barWidth, 12, 6).fill(BRAND.light);

  const ratio = Math.max(0, Math.min(1, score / max));
  if (ratio > 0) {
    doc.roundedRect(205, top, Math.max(6, barWidth * ratio), 12, 6).fill(color);
  }

  doc.fillColor(BRAND.text).font('Helvetica-Bold').fontSize(9)
    .text(`${Math.round(score)}/${max}`, 205 + barWidth + 10, top + 2, { width: 60 });

  doc.y = top + 22;
}

function bulletList(doc: Doc, items: string[], color = BRAND.text): void {
  if (!items.length) {
    doc.font('Helvetica-Oblique').fontSize(9).fillColor(BRAND.muted).text('None recorded.');
    doc.font('Helvetica').fillColor(BRAND.text);
    return;
  }
  for (const item of items) {
    ensureSpace(doc, 26);
    doc.font('Helvetica').fontSize(9.5).fillColor(color).text(`•  ${safe(item)}`, { indent: 6, width: doc.page.width - 110 });
    doc.moveDown(0.18);
  }
  doc.fillColor(BRAND.text);
}

function footer(doc: Doc): void {
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i += 1) {
    doc.switchToPage(i);
    const bottom = doc.page.height - 58;
    doc.moveTo(50, bottom).lineTo(doc.page.width - 50, bottom).strokeColor(BRAND.light).stroke();
    doc.font('Helvetica').fontSize(6.8).fillColor(BRAND.muted)
      .text(DISCLAIMER, 50, bottom + 7, { width: doc.page.width - 160, align: 'left' });
    doc.font('Helvetica-Bold').fontSize(8)
      .text(`${i - range.start + 1} / ${range.count}`, doc.page.width - 100, bottom + 12, { width: 50, align: 'right' });
  }
}

function render(build: (doc: Doc) => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    // `bufferPages` is required so the footer can be stamped on every page after
    // the content length is known.
    const doc = new PDFDocument({ size: 'A4', margin: 50, bufferPages: true, info: { Title: 'CareerPilot AI Report' } });
    const chunks: Buffer[] = [];

    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    try {
      build(doc);
      footer(doc);
      doc.end();
    } catch (error) {
      reject(error);
    }
  });
}

async function studentHeaderInfo(studentId: Types.ObjectId) {
  const profile = await StudentProfile.findById(studentId).lean();
  if (!profile) throw ApiError.notFound('Student profile');
  const user = await User.findById(profile.userId).select('fullName email').lean();
  return { profile, user };
}

