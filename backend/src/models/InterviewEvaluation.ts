import { Schema, type Document, type Types } from 'mongoose';
import { registerModel } from './registerModel';
import { InterviewMode } from '@careerpilot/shared';

export interface IInterviewEvaluation extends Document {
  _id: Types.ObjectId;
  sessionId: Types.ObjectId;
  studentId: Types.ObjectId;
  mode: InterviewMode;
  overallScore: number;
  technicalScore: number;
  communicationScore: number;
  structureScore: number;
  /**
   * Derived only from objective delivery signals (response length, filler-word
   * rate, hedging language). Never from facial expression or affect (§12).
   */
  confidenceIndicatorScore: number;
  questionsAnswered: number;
  strengths: string[];
  weaknesses: string[];
  recommendations: string[];
  perQuestion: Array<{ questionId: Types.ObjectId; question: string; score: number; feedback: string }>;
  summary: string;
  disclaimer: string;
  createdAt: Date;
  updatedAt: Date;
}

const interviewEvaluationSchema = new Schema<IInterviewEvaluation>(
  {
    sessionId: { type: Schema.Types.ObjectId, ref: 'InterviewSession', required: true, unique: true, index: true },
    studentId: { type: Schema.Types.ObjectId, ref: 'StudentProfile', required: true, index: true },
    mode: { type: String, enum: Object.values(InterviewMode), required: true, index: true },
    overallScore: { type: Number, min: 0, max: 100, required: true },
    technicalScore: { type: Number, min: 0, max: 100, default: 0 },
    communicationScore: { type: Number, min: 0, max: 100, default: 0 },
    structureScore: { type: Number, min: 0, max: 100, default: 0 },
    confidenceIndicatorScore: { type: Number, min: 0, max: 100, default: 0 },
    questionsAnswered: { type: Number, default: 0 },
    strengths: { type: [String], default: [] },
    weaknesses: { type: [String], default: [] },
    recommendations: { type: [String], default: [] },
    perQuestion: {
      type: [
        new Schema(
          {
            questionId: { type: Schema.Types.ObjectId, ref: 'InterviewQuestion' },
            question: String,
            score: Number,
            feedback: String,
          },
          { _id: false },
        ),
      ],
      default: [],
    },
    summary: { type: String, default: '' },
    disclaimer: {
      type: String,
      default:
        'This evaluation is generated by an AI prototype from the text of your answers. It measures content and delivery signals only and must not be treated as a hiring decision.',
    },
  },
  { timestamps: true, toJSON: { virtuals: true } },
);

interviewEvaluationSchema.index({ studentId: 1, mode: 1, createdAt: -1 });

export const InterviewEvaluation = registerModel<IInterviewEvaluation>('InterviewEvaluation', interviewEvaluationSchema);
