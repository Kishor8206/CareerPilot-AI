"""Split the validated examples and write the dataset manifests.

    python training/split_dataset.py        ->  data/{train,validation,test}/career_sft.jsonl

Leakage control
  * Split by LEARNER PROFILE (role + exact skill set), never by example: one
    profile produces several task types, and those must not straddle splits.
  * Two roles are held out of training and validation ENTIRELY and appear only
    in the test split. The design claim is that the model reasons from the
    knowledge in the prompt, so a new role needs no retraining; the held-out
    roles are how that claim is measured rather than asserted.
  * The audit below fails the script if any profile or prompt crosses a split.

Target proportions for the in-distribution profiles: 80 / 10 / 10.
"""
from __future__ import annotations

import hashlib
import json
import sys
import time
from collections import Counter

from common import DATA, DATASET_VERSION, KNOWLEDGE, PREPROCESSING_VERSION, VALIDATED, read_json, write_json

HELD_OUT_ROLES = ("Site Reliability Engineer", "Product Analyst")
SEED = "career-split-v1"


def bucket(profile_key: str) -> str:
    x = int(hashlib.sha256((SEED + profile_key).encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    return "train" if x < 0.80 else "validation" if x < 0.90 else "test"


def main() -> None:
    records = [json.loads(line) for line in open(VALIDATED / "career_sft.jsonl", encoding="utf-8")]
    splits: dict[str, list] = {"train": [], "validation": [], "test": []}
    for r in records:
        r["held_out_role"] = r["role"] in HELD_OUT_ROLES
        r["split"] = "test" if r["held_out_role"] else bucket(r["profile_key"])
        splits[r["split"]].append(r)

    # ---- audit: must be clean by construction; verified, not assumed
    problems = []
    names = list(splits)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            pa, pb = {r["profile_key"] for r in splits[a]}, {r["profile_key"] for r in splits[b]}
            qa = {hashlib.sha256(r["messages"][1]["content"].encode()).hexdigest() for r in splits[a]}
            qb = {hashlib.sha256(r["messages"][1]["content"].encode()).hexdigest() for r in splits[b]}
            if pa & pb or qa & qb:
                problems.append(f"{a}|{b}: {len(pa & pb)} shared profiles, {len(qa & qb)} shared prompts")
    for name in ("train", "validation"):
        leaked = sorted({r["role"] for r in splits[name]} & set(HELD_OUT_ROLES))
        if leaked:
            problems.append(f"held-out role(s) {leaked} found in {name}")
    if problems:
        print("LEAKAGE DETECTED — refusing to write splits:\n  " + "\n  ".join(problems))
        sys.exit(1)

    for name, rows in splits.items():
        (DATA / name).mkdir(parents=True, exist_ok=True)
        with open(DATA / name / "career_sft.jsonl", "w", encoding="utf-8") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")

    validation = read_json(VALIDATED / "validation_report.json")
    sources = read_json(KNOWLEDGE / "data_source_manifest.json")
    taxonomy = read_json(KNOWLEDGE / "skill_taxonomy.json")
    counts = {name: len(rows) for name, rows in splits.items()}
    stats = {name: {"examples": len(rows), "profiles": len({r["profile_key"] for r in rows}),
                    "tasks": len({r["task_code"] for r in rows}), "roles": len({r["role"] for r in rows}),
                    "mean_tokens": round(sum(r["n_tokens"] for r in rows) / max(1, len(rows)))}
             for name, rows in splits.items()}
    test_held = sum(r["held_out_role"] for r in splits["test"])

    write_json(DATA / "dataset_version.json", {
        "dataset_version": DATASET_VERSION, "preprocessing_version": PREPROCESSING_VERSION,
        "taxonomy_version": taxonomy["knowledge_version"], "created": time.strftime("%Y-%m-%d %H:%M:%S"),
        "counts": counts, "total": sum(counts.values()),
    })
    write_json(DATA / "dataset_manifest.json", {
        "dataset_version": DATASET_VERSION, "preprocessing_version": PREPROCESSING_VERSION,
        "taxonomy_version": taxonomy["knowledge_version"],
        "source_versions": [{"source": s["source"], "version": s["version"], "license": s["license"]} for s in sources["sources"]],
        "provenance": {"learner_profiles": "SYNTHETIC", "career_facts": "curated knowledge, corroborated against O*NET/ESCO/job data",
                       "targets": "generated by the deterministic planner (ai-service/app/career/planner.py)"},
        "splits": stats, "held_out_roles": list(HELD_OUT_ROLES),
        "test_composition": {"in_distribution": counts["test"] - test_held, "held_out_role": test_held},
        "split_method": "by learner profile (role + exact skill set), hash-bucketed 80/10/10; two roles held out to test only",
        "leakage_audit": "0 shared profiles and 0 shared prompts across every split pair",
        "validation_statistics": {k: validation[k] for k in ("generated", "valid", "rejected", "reject_rate", "rejects_by_reason",
                                                             "contradictory_prompts", "tokens", "output_tokens")},
        "task_counts": dict(sorted(Counter(r["task_code"] for r in records).items())),
    })
    print(f"split {len(records)} examples: " + " | ".join(f"{k} {v}" for k, v in counts.items()))
    print(f"test = {counts['test'] - test_held} in-distribution + {test_held} from held-out roles {list(HELD_OUT_ROLES)}")
    for name, s in stats.items():
        print(f"  {name:<11}{s}")
    print("leakage audit: clean (profiles, prompts, held-out roles)")


if __name__ == "__main__":
    main()
